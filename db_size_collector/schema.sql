-- Oracle DDL Script for Database Size Collector
-- Run this as the dba_db_size user or with appropriate privileges
-- Schema: dba_db_size

-- ============================================================
-- Oracle Database Sizes Table
-- ============================================================
CREATE TABLE oracle_db_sizes (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_date     DATE NOT NULL,
    hostname            VARCHAR2(100) NOT NULL,
    ip_address          VARCHAR2(45),
    instance_name       VARCHAR2(100),
    db_name             VARCHAR2(100),
    physical_size_gb    NUMBER(12,2),  -- datafile + tempfile + redo (100GB buffer)
    logical_size_gb     NUMBER(12,2),  -- dba_segments actual data
    application         VARCHAR2(200),
    environment         VARCHAR2(50),
    db_version          VARCHAR2(50),
    collection_status   VARCHAR2(20) DEFAULT 'SUCCESS',  -- SUCCESS, FAILED, PARTIAL
    error_message       VARCHAR2(500),
    created_at          TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE INDEX idx_oracle_sizes_date ON oracle_db_sizes(collection_date);
CREATE INDEX idx_oracle_sizes_host ON oracle_db_sizes(hostname, instance_name);


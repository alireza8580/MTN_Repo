-- ============================================================
-- Collection Summary Table (for monitoring)
-- ============================================================
CREATE TABLE collection_summary (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_date     DATE NOT NULL,
    platform            VARCHAR2(20) NOT NULL,  -- oracle, mysql, mongo, postgres, cassandra, mssql
    total_hosts         NUMBER(5),
    successful_hosts    NUMBER(5),
    failed_hosts        NUMBER(5),
    total_physical_gb   NUMBER(14,2),
    total_logical_gb    NUMBER(14,2),
    start_time          TIMESTAMP,
    end_time            TIMESTAMP,
    duration_seconds    NUMBER(8,2),
    created_at          TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE INDEX idx_collection_summary_date ON collection_summary(collection_date, platform);

-- ============================================================
-- Views for easy reporting
-- ============================================================

-- Daily total sizes by platform
CREATE OR REPLACE VIEW v_daily_db_sizes AS
SELECT 
    collection_date,
    platform,
    SUM(total_physical_gb) AS physical_gb,
    SUM(total_logical_gb) AS logical_gb
FROM collection_summary
GROUP BY collection_date, platform
ORDER BY collection_date DESC, platform;

-- Latest sizes per host (Oracle)
CREATE OR REPLACE VIEW v_latest_oracle_sizes AS
SELECT * FROM (
    SELECT 
        hostname,
        instance_name,
        ip_address,
        physical_size_gb,
        logical_size_gb,
        application,
        collection_date,
        ROW_NUMBER() OVER (PARTITION BY hostname, instance_name ORDER BY collection_date DESC) AS rn
    FROM oracle_db_sizes
    WHERE collection_status = 'SUCCESS'
)
WHERE rn = 1;

-- Latest sizes per host (MySQL)
CREATE OR REPLACE VIEW v_latest_mysql_sizes AS
SELECT * FROM (
    SELECT 
        hostname,
        port,
        ip_address,
        physical_size_gb,
        logical_size_gb,
        application,
        role,
        collection_date,
        ROW_NUMBER() OVER (PARTITION BY hostname, port ORDER BY collection_date DESC) AS rn
    FROM mysql_db_sizes
    WHERE collection_status = 'SUCCESS'
)
WHERE rn = 1;

-- Weekly growth report
CREATE OR REPLACE VIEW v_weekly_growth AS
SELECT 
    platform,
    TRUNC(collection_date, 'IW') AS week_start,
    MAX(total_physical_gb) - MIN(total_physical_gb) AS physical_growth_gb,
    MAX(total_logical_gb) - MIN(total_logical_gb) AS logical_growth_gb
FROM collection_summary
WHERE collection_date >= TRUNC(SYSDATE) - 90
GROUP BY platform, TRUNC(collection_date, 'IW')
ORDER BY week_start DESC, platform;

